#!/usr/bin/env python3

"""Fetches recent IntelliJ IDEA and Android Studio releases and records the Kotlin
compiler version each one bundles, as alias mappings.

The bundled version is read straight out of the IDE's own library declaration in
intellij-community, so it is already a coordinate published to intellij-dependencies -
usually an `-ij` version. No search for an equivalent `dev` build is involved; the
mapping names exactly what the IDE ships.

Works entirely via HTTP/API calls - no IDE binaries are downloaded.

Usage:
  ./fetch-all-ide-kotlin-versions.py [--channels stable,canary,beta,eap,rc]

Dependencies: python3, gh (GitHub CLI, authenticated)
"""

import argparse
import json
import os
import re
import subprocess
import sys
import urllib.request
import xml.etree.ElementTree as ET
from collections import OrderedDict

FILE_PATH = ".idea/libraries/kotlinc_kotlin_compiler_common.xml"
RAW_GH_BASE = "https://raw.githubusercontent.com/JetBrains/intellij-community"

# Where the IDE itself gets its compiler from, and therefore where every alias target
# has to resolve. Only used to sanity-check the versions we write.
INTELLIJ_DEPENDENCIES = "https://redirector.kotlinlang.org/maven/intellij-dependencies"
PUBLISHED_ARTIFACT = "kotlin-compiler"


def parse_kotlin_base_version(version_str):
    """Extract the numeric base (major, minor, patch) from a Kotlin version string.
    E.g. '2.2.20-ij252-24' -> (2, 2, 20), '2.3.20-dev-3964' -> (2, 3, 20)."""
    m = re.match(r"^(\d+)\.(\d+)\.(\d+)", version_str)
    if m:
        return (int(m.group(1)), int(m.group(2)), int(m.group(3)))
    return (0, 0, 0)


HEADER_LINES = {
    "# IDE Kotlin version alias mappings",
    "# Generated by fetch-all-ide-kotlin-versions.py",
    "# Format: <ide-version>=<kotlin-version>",
    "#",
}


def read_all_existing_entries(filepath):
    """Read existing ide-mappings.txt and return:
    - entries: OrderedDict of version -> target
    - comments: OrderedDict of version -> list of comment strings (without '# ' prefix)
    """
    entries = OrderedDict()
    comments = OrderedDict()
    if not os.path.exists(filepath):
        return entries, comments
    pending_comments = []
    with open(filepath) as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("#"):
                if line not in HEADER_LINES:
                    if line.startswith("# "):
                        pending_comments.append(line[2:])
                    else:
                        pending_comments.append(line[1:])
            elif "=" in line:
                version, target = line.split("=", 1)
                entries[version] = target
                comments[version] = pending_comments
                pending_comments = []
            else:
                pending_comments = []
    return entries, comments


def _grep_file(relative_path, pattern):
    """First capture group of pattern over a file relative to this script, or None."""
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), relative_path)
    try:
        with open(path) as f:
            for line in f:
                m = re.match(pattern, line.strip())
                if m:
                    return m.group(1)
    except FileNotFoundError:
        pass
    return None


def read_min_kotlin_version():
    """The oldest Kotlin version worth mapping an IDE onto.

    That is the oldest one the dev kit supports, not the one this build compiles
    against - an IDE bundling an older compiler than we support needs no mapping, but
    one bundling anything we do support does. Falls back to the build's own Kotlin
    version when the property is absent."""
    return _grep_file(
        "../gradle.properties",
        r"^kotlin\.compiler\.plugin\.devkit\.minCliVersion\s*=\s*(\S+)",
    ) or _grep_file("../gradle/libs.versions.toml", r'^kotlin\s*=\s*"([^"]+)"')


# ─── HTTP / GitHub helpers ───────────────────────────────────────────────────


def fetch_url(url):
    """Fetch a URL and return (body, http_status)."""
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "fetch-ide-kotlin-versions"})
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.read().decode("utf-8"), resp.status
    except urllib.error.HTTPError as e:
        return "", e.code
    except Exception:
        return "", 0


def gh_api(endpoint, jq_filter=None):
    """Call gh api and return the parsed JSON, or raw string if jq_filter is used."""
    cmd = ["gh", "api", endpoint]
    if jq_filter:
        cmd += ["-q", jq_filter]
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
        if result.returncode != 0:
            return None
        if jq_filter:
            return result.stdout.strip()
        return json.loads(result.stdout) if result.stdout.strip() else None
    except Exception:
        return None


# ─── Published versions ──────────────────────────────────────────────────────

# None until fetched, and left as None if the repository could not be read, which
# turns the check below into a no-op.
_published_versions = None


def published_versions():
    """Every PUBLISHED_ARTIFACT version in intellij-dependencies, or None if unreadable."""
    global _published_versions
    if _published_versions is not None:
        return _published_versions

    url = f"{INTELLIJ_DEPENDENCIES}/org/jetbrains/kotlin/{PUBLISHED_ARTIFACT}/maven-metadata.xml"
    body, status = fetch_url(url)
    if status != 200 or not body:
        print(f"  WARNING: Failed to fetch {PUBLISHED_ARTIFACT} metadata (HTTP {status});"
              " alias targets will not be checked", file=sys.stderr)
        return None

    try:
        root = ET.fromstring(body)
    except ET.ParseError as e:
        print(f"  WARNING: Malformed {PUBLISHED_ARTIFACT} metadata ({e})", file=sys.stderr)
        return None

    _published_versions = {
        (elem.text or "").strip() for elem in root.findall(".//versions/version")
    }
    print(f"  Found {len(_published_versions)} published {PUBLISHED_ARTIFACT} versions")
    return _published_versions


# ─── Kotlin version resolution ───────────────────────────────────────────────

_kotlin_version_cache = {}


def fetch_kotlin_version(tag):
    """Fetch the Kotlin version an intellij-community tag declares, or None."""
    if tag in _kotlin_version_cache:
        return _kotlin_version_cache[tag]
    body, status = fetch_url(f"{RAW_GH_BASE}/{tag}/{FILE_PATH}")
    version = None
    if status == 200:
        m = re.search(r'kotlin-compiler-common-for-ide:([^"]+)', body)
        if m:
            version = m.group(1)
    _kotlin_version_cache[tag] = version
    return version


def build_key(build):
    """Numeric components of a platform build number, for ordering."""
    return tuple(int(p) if p.isdigit() else 0 for p in build.split("."))


_platform_tags_cache = {}


def platform_tags(major):
    """Every idea/<major>.* tag in intellij-community, as build numbers, ascending."""
    if major in _platform_tags_cache:
        return _platform_tags_cache[major]
    raw = gh_api(
        f"repos/JetBrains/intellij-community/git/matching-refs/tags/idea/{major}.",
        jq_filter=".[].ref",
    )
    builds = sorted(
        (t.removeprefix("refs/tags/idea/") for t in (raw or "").splitlines() if t.strip()),
        key=build_key,
    )
    _platform_tags_cache[major] = builds
    return builds


def resolve_kotlin_version_for_build(build):
    """Resolve a platform build to the Kotlin version it bundles.

    Only a tag records which version a build ships, so the newest tag at or below the
    build is the last word on it. Reaching *upwards* instead would claim a version the
    build predates; a build below every tag in its platform is left unmapped, and
    CompilerVersionAliases then falls back to the version the IDE reports.

    Returns (tag, kotlin_version, is_exact_match)."""
    key = build_key(build)
    candidates = [b for b in platform_tags(build.split(".")[0]) if build_key(b) <= key]
    # Walk downwards, since a tag can predate the library file we read
    for candidate in reversed(candidates):
        kv = fetch_kotlin_version(f"idea/{candidate}")
        if kv:
            return f"idea/{candidate}", kv, candidate == build
    return None, None, False


# ─── Fetch IDE releases ─────────────────────────────────────────────────────


def fetch_intellij_releases(channels):
    """Fetch every IntelliJ IDEA release in the given channels from the JetBrains API."""
    type_map = {"stable": "release", "eap": "eap", "rc": "rc"}
    types = [type_map[c] for c in channels if c in type_map]
    if not types:
        return []

    type_param = ",".join(types)
    url = f"https://data.services.jetbrains.com/products/releases?code=IIU&type={type_param}"
    body, status = fetch_url(url)
    if status != 200 or not body:
        print(f"  WARNING: Failed to fetch IntelliJ releases (HTTP {status})", file=sys.stderr)
        return []

    data = json.loads(body)
    ch_labels = {"release": "stable", "eap": "eap", "rc": "rc"}

    releases = []
    for _product_code, items in data.items():
        for r in items:
            build = r.get("build", "")
            version = r.get("version", "")
            ch = ch_labels.get(r.get("type", "release"), r.get("type", "release"))
            if build:
                releases.append({
                    "ide_name": f"IntelliJ IDEA {version} ({ch})",
                    "platform_build": build,
                })

    return releases


def fetch_android_studio_releases(channels):
    """Fetch Android Studio releases from updates.xml."""
    url = "https://dl.google.com/android/studio/patches/updates.xml"
    body, status = fetch_url(url)
    if status != 200 or not body:
        print(f"  WARNING: Failed to fetch Android Studio releases (HTTP {status})", file=sys.stderr)
        return []

    root = ET.fromstring(body)
    releases = []
    for channel_elem in root.findall(".//channel"):
        channel_id = channel_elem.get("id", "")
        if "release" in channel_id:
            ch = "stable"
        elif "beta" in channel_id:
            ch = "beta"
        elif "rc" in channel_id:
            ch = "rc"
        elif "eap" in channel_id:
            ch = "canary"
        else:
            ch = "unknown"

        if ch not in channels:
            continue

        for build_elem in channel_elem.findall("build"):
            number = build_elem.get("number", "")
            api_version = build_elem.get("apiVersion", "")
            version = build_elem.get("version", "")
            name = build_elem.get("name", version)
            display = name or version or number

            if not api_version:
                continue

            releases.append({
                "ide_name": f"Android Studio {display} ({ch})",
                "platform_build": api_version.removeprefix("AI-"),
            })

    return releases


# ─── Main ────────────────────────────────────────────────────────────────────


def main():
    parser = argparse.ArgumentParser(description="Fetch IDE Kotlin version aliases")
    parser.add_argument(
        "--channels",
        default="stable,canary,beta,eap,rc",
        help="Comma-separated list of channels (default: stable,canary,beta,eap,rc)",
    )
    detected_kotlin = read_min_kotlin_version()
    default_min_kotlin = detected_kotlin or "2.2.20"
    parser.add_argument(
        "--min-kotlin",
        default=default_min_kotlin,
        help=f"Minimum Kotlin base version to include (default: {default_min_kotlin}"
             + (", detected from the build)" if detected_kotlin else ")"),
    )
    args = parser.parse_args()
    channels = set(args.channels.split(","))
    min_kotlin = parse_kotlin_base_version(args.min_kotlin)

    # Read existing entries to preserve them (additive mode)
    script_dir = os.path.dirname(os.path.abspath(__file__))
    output_file = os.path.join(script_dir, "src/main/resources/META-INF/org/jetbrains/kotlin/compiler/plugin/devkit/ide-mappings.txt")
    existing_entries, existing_comments = read_all_existing_entries(output_file)
    if existing_entries:
        print(f"Loaded {len(existing_entries)} existing entries from ide-mappings.txt")

    # Check for gh CLI
    try:
        subprocess.run(["gh", "auth", "status"], capture_output=True, timeout=10)
    except FileNotFoundError:
        print("Error: 'gh' (GitHub CLI) is required but not found.", file=sys.stderr)
        print("Install it from https://cli.github.com/", file=sys.stderr)
        sys.exit(1)

    # Fetch releases
    print("Fetching IntelliJ IDEA releases...")
    ij_releases = fetch_intellij_releases(channels)
    print(f"  Found {len(ij_releases)} IntelliJ releases")

    print("Fetching Android Studio releases...")
    as_releases = fetch_android_studio_releases(channels)
    print(f"  Found {len(as_releases)} Android Studio releases")

    all_releases = ij_releases + as_releases

    if not all_releases:
        print(f"\nNo releases found for channels: {args.channels}")
        return

    print(f"\nTotal: {len(all_releases)} IDE releases")
    print(f"Filtering to Kotlin >= {args.min_kotlin}")

    # Deduplicate by platform build number — multiple IDE entries can share the
    # same underlying build, so we only need to resolve each build once.
    unique_builds = OrderedDict()  # platform_build -> [release_dicts]
    for release in all_releases:
        unique_builds.setdefault(release["platform_build"], []).append(release)

    print(f"Unique platform builds: {len(unique_builds)}")
    print()

    resolved = {}  # build -> kotlin_version

    for build, entries in unique_builds.items():
        representative = entries[0]["ide_name"]
        major = build.split(".")[0]

        # 221 is the first platform to bundle Kotlin
        if (int(major) if major.isdigit() else 0) < 221:
            continue

        print(f"━━━ {representative} (build {build}) ━━━")

        tag, kotlin_version, is_exact_match = resolve_kotlin_version_for_build(build)

        if not kotlin_version:
            print("  Could not resolve Kotlin version, skipping")
            print()
            continue

        # Skip if below minimum Kotlin version
        if parse_kotlin_base_version(kotlin_version) < min_kotlin:
            print(f"  Kotlin {kotlin_version} < {args.min_kotlin}, skipping")
            print()
            continue

        print(f"  Tag: {tag}" + ("" if is_exact_match else " (fallback)"))
        print(f"  Kotlin version: {kotlin_version}")
        print()

        resolved[build] = kotlin_version

    # Additive merge: start with existing entries, add/update from new results
    final_map = OrderedDict(existing_entries)
    final_comments = OrderedDict(
        (version, list(existing_comments.get(version, []))) for version in existing_entries
    )

    additions = 0
    updates = 0
    for build, kotlin_version in resolved.items():
        names = [r["ide_name"] for r in unique_builds[build]]
        existing_target = final_map.get(build)

        if existing_target is None:
            final_map[build] = kotlin_version
            final_comments[build] = names
            additions += 1
            continue

        # Never override CLI_ONLY entries, but do merge their comments
        if existing_target != "CLI_ONLY" and existing_target != kotlin_version:
            print(f"  Updating {build}: {existing_target} -> {kotlin_version}")
            final_map[build] = kotlin_version
            updates += 1
        merged = final_comments.setdefault(build, [])
        merged.extend(n for n in names if n not in merged)

    print(f"\n  {additions} new entries, {updates} updated entries")

    print("\nChecking alias targets against intellij-dependencies...")
    published = published_versions()
    if published is not None:
        unpublished = sorted(
            {t for t in final_map.values() if t != "CLI_ONLY" and t not in published}
        )
        for target in unpublished:
            print(f"  WARNING: {target} is not published as {PUBLISHED_ARTIFACT}"
                  " in intellij-dependencies", file=sys.stderr)

    # Output
    print()
    print("═══════════════════════════════════════════════════════════════════════════")
    print(" RESULTS")
    print("═══════════════════════════════════════════════════════════════════════════")
    print()

    if not final_map:
        print("No aliases found.")
        print()
        return

    # Table output — one row per unique mapping
    print(f"{'IDE (representative)':<45} {'IDE Build':<25} → Alias Target")
    print("─" * 95)
    for build in sorted(final_map.keys()):
        names = final_comments.get(build, [])
        representative = names[0] if names else "?"
        extra = f" (+{len(names) - 1} more)" if len(names) > 1 else ""
        print(f"{representative + extra:<45} {build:<25} → {final_map[build]}")

    print()
    print("═══════════════════════════════════════════════════════════════════════════")
    print()

    with open(output_file, "w") as f:
        f.write("# IDE Kotlin version alias mappings\n")
        f.write("# Generated by fetch-all-ide-kotlin-versions.py\n")
        f.write("# Format: <ide-version>=<kotlin-version>\n")
        f.write("#\n")

        for build in sorted(final_map.keys()):
            for comment in final_comments.get(build, []):
                f.write(f"# {comment}\n")
            f.write(f"{build}={final_map[build]}\n")

    print(f"Written to: {output_file}")
    print()


if __name__ == "__main__":
    main()
