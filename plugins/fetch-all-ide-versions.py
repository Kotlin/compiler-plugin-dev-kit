#!/usr/bin/env python3

"""Fetches IntelliJ IDEA and Android Studio releases and writes them to the
`ide-versions.txt` plugins resource, grouped by product and release channel.

The grouping is the point: a build number alone doesn't say whether it was a stable
release, an RC or an EAP/canary, and neither does anything an IDE exposes at runtime,
so the channel has to be recorded here while the APIs still say it.

Entries are keyed on the *platform* build - the same key space as version-resolution's
ide-mappings.txt, which is what an Android Studio build number resolves against. Several
Android Studio releases share one platform build; the newest of them wins the entry.

Neither source promises to keep serving a build forever, so this is additive: existing
entries are never dropped, only updated.

Usage:
  ./fetch-all-ide-versions.py [--channels stable,rc,eap,beta,canary] [--min-platform 221]

Dependencies: python3
"""

import argparse
import json
import os
import sys
import urllib.request
from collections import OrderedDict

OUTPUT_PATH = "src/main/resources/META-INF/org/jetbrains/kotlin/compiler/plugin/devkit/ide-versions.txt"

HEADER_LINES = [
    "# IntelliJ IDEA and Android Studio releases, grouped by release channel",
    "# Generated by fetch-all-ide-versions.py",
    "# Format: [<product>-<channel>] sections of <platform-build>=<IDE version>",
    "#",
]

# 253 (2025.3) is the lowest platform we care about
DEFAULT_MIN_PLATFORM = 253

# Written in this order; anything else found in an existing file is appended after.
SECTION_ORDER = [
    "idea-stable",
    "idea-rc",
    "idea-eap",
    "studio-stable",
    "studio-rc",
    "studio-beta",
    "studio-canary",
]

IDEA_CHANNELS = {"release": "stable", "rc": "rc", "eap": "eap"}
# A `Patch` is a stable release, and the handful of ancient `Preview`s are canaries.
STUDIO_CHANNELS = {
    "release": "stable",
    "patch": "stable",
    "rc": "rc",
    "beta": "beta",
    "canary": "canary",
    "preview": "canary",
}

ALL_CHANNELS = sorted({*IDEA_CHANNELS.values(), *STUDIO_CHANNELS.values()})


def build_key(build):
    """Sort key for a build number like '253.29346.138' or '111.69'."""
    return tuple(int(p) if p.isdigit() else 0 for p in build.split("."))


def platform_baseline(build):
    head = build.split(".")[0]
    return int(head) if head.isdigit() else 0


# ─── HTTP ────────────────────────────────────────────────────────────────────


def fetch_url(url):
    """Fetch a URL and return (body, http_status)."""
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "fetch-all-ide-versions"})
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.read().decode("utf-8"), resp.status
    except urllib.error.HTTPError as e:
        return "", e.code
    except Exception:
        return "", 0


# ─── Fetch IDE releases ──────────────────────────────────────────────────────


def fetch_intellij_releases(channels):
    """IntelliJ IDEA releases from the JetBrains data service.

    Yields dicts of platform_build / channel / version / build_key. IDEA build numbers
    are unique per release, so no two entries ever collide.
    """
    types = [t for t, ch in IDEA_CHANNELS.items() if ch in channels]
    if not types:
        return []

    url = f"https://data.services.jetbrains.com/products/releases?code=IIU&type={','.join(types)}"
    body, status = fetch_url(url)
    if status != 200 or not body:
        print(f"  WARNING: Failed to fetch IntelliJ releases (HTTP {status})", file=sys.stderr)
        return []

    releases = []
    for _product_code, items in json.loads(body).items():
        for r in items:
            build = r.get("build", "")
            version = r.get("version", "")
            channel = IDEA_CHANNELS.get(r.get("type", "release"))
            if not build or not version or channel not in channels:
                continue
            releases.append({
                "product": "idea",
                "channel": channel,
                "platform_build": build,
                "version": version,
                # Unique per release, so the tiebreak never fires.
                "tiebreak": build_key(build),
            })
    return releases


def fetch_android_studio_releases(channels):
    """Android Studio releases from the list JetBrains keeps for its own IDE tooling.

    Google's own updates.xml only serves the few builds currently offered per channel; this
    one goes back to 2017 and states the channel outright.

    Keyed on `platformBuild` rather than on the full Studio build, so many releases can land
    on one entry; `tiebreak` decides which.
    """
    url = "https://jb.gg/android-studio-releases-list.json"
    body, status = fetch_url(url)
    if status != 200 or not body:
        print(f"  WARNING: Failed to fetch Android Studio releases (HTTP {status})", file=sys.stderr)
        return []

    releases = []
    for item in json.loads(body).get("content", {}).get("item", []):
        platform_build = item.get("platformBuild", "")
        channel = STUDIO_CHANNELS.get(item.get("channel", "").lower())
        if not platform_build or channel not in channels:
            continue
        # `name` is '<codename> | <version>', e.g. 'Android Studio Quail 3 | 2026.1.3'.
        name = item.get("name", "")
        version = name.rpartition("|")[2].strip() or item.get("version", "")
        if not version:
            continue
        releases.append({
            "product": "studio",
            "channel": channel,
            "platform_build": platform_build,
            "version": version,
            # The full Studio build, which orders releases sharing a platform build.
            "tiebreak": build_key(item.get("build", "").removeprefix("AI-")),
        })
    return releases


# ─── Existing file ───────────────────────────────────────────────────────────


def read_existing(filepath):
    """Parse ide-versions.txt into an OrderedDict of section -> {build: version}."""
    sections = OrderedDict()
    if not os.path.exists(filepath):
        return sections
    current = None
    with open(filepath) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("[") and line.endswith("]"):
                current = line[1:-1]
                sections.setdefault(current, OrderedDict())
            elif "=" in line and current:
                build, version = line.split("=", 1)
                sections[current][build] = version
    return sections


# ─── Main ────────────────────────────────────────────────────────────────────


def main():
    parser = argparse.ArgumentParser(description="Fetch IDE releases grouped by channel")
    parser.add_argument(
        "--channels",
        default=",".join(ALL_CHANNELS),
        help=f"Comma-separated channels to record (default: all of {','.join(ALL_CHANNELS)})",
    )
    parser.add_argument(
        "--min-platform",
        type=int,
        default=DEFAULT_MIN_PLATFORM,
        help=f"Lowest platform baseline to record (default: {DEFAULT_MIN_PLATFORM}, the "
             "lowest we care about)",
    )
    parser.add_argument("--max-platform", type=int, help="Highest platform baseline to record")
    args = parser.parse_args()

    channels = set(args.channels.split(","))
    unknown = channels - set(ALL_CHANNELS)
    if unknown:
        print(f"Error: unknown channel(s): {', '.join(sorted(unknown))}", file=sys.stderr)
        sys.exit(1)

    script_dir = os.path.dirname(os.path.abspath(__file__))
    output_file = os.path.join(script_dir, OUTPUT_PATH)
    existing = read_existing(output_file)
    if existing:
        total = sum(len(v) for v in existing.values())
        print(f"Loaded {total} existing entries from ide-versions.txt")

    print("Fetching IntelliJ IDEA releases...")
    ij_releases = fetch_intellij_releases(channels)
    print(f"  Found {len(ij_releases)} IntelliJ releases")

    print("Fetching Android Studio releases...")
    as_releases = fetch_android_studio_releases(channels)
    print(f"  Found {len(as_releases)} Android Studio releases")

    all_releases = ij_releases + as_releases
    if not all_releases:
        print(f"\nNo releases found for channels: {args.channels}")
        return

    # Collapse to one entry per (section, platform build), newest release winning.
    fetched = {}  # (section, build) -> release
    skipped_platform = 0
    for release in all_releases:
        baseline = platform_baseline(release["platform_build"])
        if baseline < args.min_platform or (args.max_platform and baseline > args.max_platform):
            skipped_platform += 1
            continue
        key = (f"{release['product']}-{release['channel']}", release["platform_build"])
        previous = fetched.get(key)
        if previous is None or previous["tiebreak"] < release["tiebreak"]:
            fetched[key] = release

    print(f"  {len(fetched)} unique platform builds, {skipped_platform} outside the platform range")

    # Additive merge: existing entries are kept, and only updated when the version differs.
    final = OrderedDict((section, OrderedDict(entries)) for section, entries in existing.items())
    additions = 0
    updates = 0
    for (section, build), release in fetched.items():
        entries = final.setdefault(section, OrderedDict())
        version = release["version"]
        if build not in entries:
            entries[build] = version
            additions += 1
        elif entries[build] != version:
            print(f"  Updating [{section}] {build}: {entries[build]} -> {version}")
            entries[build] = version
            updates += 1

    print(f"\n  {additions} new entries, {updates} updated entries")

    print()
    print("═══════════════════════════════════════════════════════════════════════════")
    print(" RESULTS")
    print("═══════════════════════════════════════════════════════════════════════════")
    print()

    sections = [s for s in SECTION_ORDER if final.get(s)]
    sections += [s for s in final if s not in SECTION_ORDER and final[s]]
    for section in sections:
        builds = sorted(final[section], key=build_key)
        print(f"{section:<16} {len(builds):>4}   {builds[0]} ({final[section][builds[0]]}) "
              f"… {builds[-1]} ({final[section][builds[-1]]})")
    print()

    os.makedirs(os.path.dirname(output_file), exist_ok=True)
    with open(output_file, "w") as f:
        for line in HEADER_LINES:
            f.write(f"{line}\n")
        for section in sections:
            f.write(f"\n[{section}]\n")
            for build in sorted(final[section], key=build_key):
                f.write(f"{build}={final[section][build]}\n")

    print(f"Written to: {output_file}")
    print()


if __name__ == "__main__":
    main()
