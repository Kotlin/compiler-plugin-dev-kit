#!/usr/bin/env python3

"""Fetches every Kotlin release published to Maven Central and writes them, one per line,
to the `kotlin-versions.txt` plugins resource.

`dev` builds are deliberately absent: they never reach Maven Central, and older ones
get pruned, so they stay author-supplied rather than discovered.

Runs off a single maven-metadata.xml request - no auth, no tooling.

Usage:
  ./fetch-all-kotlin-versions.py [--artifact kotlin-compiler-embeddable]

Dependencies: python3
"""

import argparse
import os
import sys
import urllib.request
import xml.etree.ElementTree as ET

MAVEN_CENTRAL = "https://repo1.maven.org/maven2"
DEFAULT_ARTIFACT = "kotlin-compiler-embeddable"
OUTPUT_PATH = "src/main/resources/META-INF/org/jetbrains/kotlin/compiler/plugin/devkit/kotlin-versions.txt"

HEADER_LINES = [
    "# Every Kotlin release published to Maven Central",
    "# Generated by fetch-all-kotlin-versions.py",
    "# Format: one version per line, in publication order. `dev` builds are not listed here.",
    "#",
]


def fetch_all_versions(artifact):
    """Every version of org.jetbrains.kotlin:<artifact> on Maven Central."""
    url = f"{MAVEN_CENTRAL}/org/jetbrains/kotlin/{artifact}/maven-metadata.xml"
    req = urllib.request.Request(url, headers={"User-Agent": "fetch-all-kotlin-versions"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        body = resp.read().decode("utf-8")
    root = ET.fromstring(body)
    return [e.text.strip() for e in root.findall(".//versions/version") if e.text and e.text.strip() and (e.text.strip()[0] not in ["0", "1"])]


def main():
    parser = argparse.ArgumentParser(description="Fetch all published Kotlin versions")
    parser.add_argument(
        "--artifact",
        default=DEFAULT_ARTIFACT,
        help=f"Artifact whose publications define an existing version (default: {DEFAULT_ARTIFACT})",
    )
    args = parser.parse_args()

    print(f"Fetching org.jetbrains.kotlin:{args.artifact} versions from Maven Central...")
    try:
        versions = fetch_all_versions(args.artifact)
    except Exception as e:
        print(f"Error: failed to fetch maven-metadata.xml ({e})", file=sys.stderr)
        sys.exit(1)
    print(f"  Found {len(versions)} versions, {versions[0]} … {versions[-1]}")

    script_dir = os.path.dirname(os.path.abspath(__file__))
    output_file = os.path.join(script_dir, OUTPUT_PATH)
    os.makedirs(os.path.dirname(output_file), exist_ok=True)
    with open(output_file, "w") as f:
        for line in HEADER_LINES:
            f.write(f"{line}\n")
        for version in versions:
            f.write(f"{version}\n")

    print(f"Written to: {output_file}")


if __name__ == "__main__":
    main()
