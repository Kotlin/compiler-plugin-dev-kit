#!/usr/bin/env python3

"""Maintains `kotlin-modules.txt`: every `org.jetbrains.kotlin` module whose version the dev
kit has to force, mapped to the name that module goes by in intellij-dependencies.

The modules discovered are the ones a consumer can actually name: everything in `dev`, which
is the normal track, plus everything in intellij-dependencies, which is the IDE one.
`bootstrap` is a superset of `dev` and is still deliberately not listed - what it adds are
`-for-ide` modules that landed there by historical accident, for a version or two only, and
which have no non-IDE artifact to be forced onto in the first place.

The IDE track renames some modules, and the rename is *not* mechanical:
`kotlin-compiler-internal-test-framework` does exist in intellij-dependencies under its own
name, yet is published too rarely to rely on, so it has to map onto
`kotlin-compiler-tests-for-ide` instead. Only a human can tell those apart, so this script
never invents a mapping and never checks one - it only reports what is missing. A mapping
that names something unpublished will fail loudly at resolution time anyway.

The file is therefore hand-curated and this script is its gate:

  - Every discovered module must have a mapping. `foo=foo` is a perfectly good one, for the
    many modules the IDE track publishes unrenamed, and so are the two sentinels:
    `UNSUPPORTED` for a module the IDE track has nothing to offer in place of, and `DEAD` for
    one that is not published on either track any more. Both say "a human looked and there is
    no name to use here", which is what distinguishes them from a blank.
  - A module with no mapping yet is written out as `foo=` and the run fails, so a new Kotlin
    module cannot slip in unnoticed. Fill the mapping in and re-run.
  - An empty mapping is fatal however long it has been there. A run that leaves one behind
    fails exactly like the run that added it, so the gate cannot be passed by re-running.
  - Existing mappings and the comments above them are preserved verbatim. Comments are the
    place to record *why* a mapping is what it is.

Exit codes are distinct, so a caller can tell the two failures apart:
  0  every module is mapped
  2  some are not, and a human has to say what they map to
  1  the run itself failed - bad arguments, or the listing could not be read

Runs off one directory listing plus one HEAD per candidate - no auth, no tooling.

Usage:
  ./fetch-all-kotlin-modules.py [--repositories dev,intellij-dependencies]

Dependencies: python3
"""

import argparse
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from collections import OrderedDict
from concurrent.futures import ThreadPoolExecutor
from html.parser import HTMLParser

REDIRECTOR = "https://redirector.kotlinlang.org/maven"
# The names a consumer would write: `dev` for the normal track, intellij-dependencies for the
# IDE one. `bootstrap` is a superset of `dev` but is not one of these - see the module docstring.
DEFAULT_REPOSITORIES = ["dev", "intellij-dependencies"]
GROUP = "org.jetbrains.kotlin"
OUTPUT_PATH = "src/main/resources/META-INF/org/jetbrains/kotlin/compiler/plugin/devkit/kotlin-modules.txt"

USER_AGENT = "fetch-all-kotlin-modules"
PROBE_WORKERS = 16

# Separates "the file needs a human" from "the run broke", which a caller wants to retry.
EXIT_NEEDS_MAPPING = 2

HEADER_LINES = [
    f"# Every {GROUP} module the dev kit forces a version on, mapped to the name it",
    "# goes by in intellij-dependencies. An identity mapping is normal; an empty one is not.",
    "# UNSUPPORTED means the IDE track has nothing to offer in its place, DEAD that the module",
    "# is not published on either track any more.",
    "# Generated by fetch-all-kotlin-modules.py, which only ever adds empty mappings -",
    "# filling them in is a human's job, because the IDE track's renames are not mechanical.",
    "# Format: <module>=<intellij-dependencies module>",
]


class DirectoryListing(HTMLParser):
    """Collects the `href`s of a Maven directory listing."""

    def __init__(self):
        super().__init__()
        self.hrefs = []

    def handle_starttag(self, tag, attrs):
        if tag == "a":
            href = dict(attrs).get("href")
            if href:
                self.hrefs.append(href)


def group_path(group):
    return group.replace(".", "/")


def repository_url(name):
    """A repository name resolves through the redirector; a URL is taken as given."""
    return name.rstrip("/") if "://" in name else f"{REDIRECTOR}/{name.strip('/')}"


def list_child_directories(repository, group):
    """The names of the directories directly under a group's path.

    Hrefs are matched against the group path rather than trusted blindly, so the parent
    link and any repository chrome drop out on their own.
    """
    base = f"{repository}/{group_path(group)}/"
    req = urllib.request.Request(base, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=30) as resp:
        # The redirector hands off to another host, so relative hrefs resolve against it.
        listing_url, body = resp.url, resp.read().decode("utf-8", "replace")

    parser = DirectoryListing()
    parser.feed(body)

    prefix = group_path(group)
    names = []
    for href in parser.hrefs:
        path = urllib.parse.urlparse(urllib.parse.urljoin(listing_url, href)).path
        if not path.endswith("/"):
            continue
        head, _, name = path.rstrip("/").rpartition("/")
        if name and head.endswith(prefix) and name not in names:
            names.append(name)
    return names


def has_metadata(repository, group, name):
    """Whether a directory is a module of the group rather than a nested group."""
    url = f"{repository}/{group_path(group)}/{name}/maven-metadata.xml"
    req = urllib.request.Request(url, method="HEAD", headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.status == 200
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return False
        raise


def modules_in(repository, group):
    """A repository's modules of the group.

    Not every directory at that level is one: the rest are nested groups
    (`org.jetbrains.kotlin.jvm` and friends, mostly Gradle plugin markers) whose contents
    belong to a different group and so could never match a request for this one. Having a
    `maven-metadata.xml` is what tells the two apart.
    """
    names = list_child_directories(repository, group)
    with ThreadPoolExecutor(max_workers=PROBE_WORKERS) as pool:
        found = list(pool.map(lambda n: has_metadata(repository, group, n), names))
    modules = {n for n, is_module in zip(names, found) if is_module}
    nested = {n for n, is_module in zip(names, found) if not is_module}
    return modules, nested


def list_modules(repositories, group):
    """The union of the group's modules across the given repositories."""
    modules, nested = set(), set()
    for name in repositories:
        url = repository_url(name)
        print(f"Listing {group} in {url}...")
        found, skipped = modules_in(url, group)
        print(f"  {len(found)} modules, {len(skipped)} nested groups")
        modules |= found
        nested |= skipped
    return modules, nested - modules


def read_existing_mappings(filepath):
    """The mappings already in the file, with the comment block above each one.

    Comments carry a human's reasoning, so they travel with their entry rather than being
    rewritten. A blank line ends a comment block without attaching it to anything, which is
    what keeps the header out of the first entry's comments even if its wording changes.
    """
    entries = OrderedDict()
    comments = OrderedDict()
    if not os.path.exists(filepath):
        return entries, comments
    pending = []
    with open(filepath) as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("#"):
                if line not in HEADER_LINES:
                    pending.append(line[2:] if line.startswith("# ") else line[1:])
            elif "=" in line:
                module, target = line.split("=", 1)
                entries[module.strip()] = target.strip()
                comments[module.strip()] = pending
                pending = []
            else:
                pending = []
    return entries, comments


def write_mappings(filepath, entries, comments):
    os.makedirs(os.path.dirname(filepath) or ".", exist_ok=True)
    with open(filepath, "w") as f:
        for line in HEADER_LINES:
            f.write(f"{line}\n")
        # Separates the header from the first entry's own comments, whatever it says.
        f.write("\n")
        for module in sorted(entries):
            for comment in comments.get(module, []):
                f.write(f"# {comment}\n")
            f.write(f"{module}={entries[module]}\n")


def main():
    parser = argparse.ArgumentParser(description=f"Maintain the {GROUP} module mappings")
    parser.add_argument(
        "--repositories",
        default=",".join(DEFAULT_REPOSITORIES),
        help="Comma-separated repository names (or URLs) defining the modules to map"
        f" (default: {','.join(DEFAULT_REPOSITORIES)})",
    )
    args = parser.parse_args()
    repositories = [r.strip() for r in args.repositories.split(",") if r.strip()]
    if not repositories:
        print("Error: no repositories given", file=sys.stderr)
        sys.exit(1)

    try:
        modules, nested = list_modules(repositories, GROUP)
    except Exception as e:
        # Writing a partial list would look complete, so leave the file alone.
        print(f"Error: failed to list {GROUP} ({e})", file=sys.stderr)
        sys.exit(1)

    if not modules:
        print(f"Error: {GROUP} has no modules, refusing to rewrite the file", file=sys.stderr)
        sys.exit(1)
    print(f"\n{len(modules)} modules to map")
    if nested:
        print(f"  {len(nested)} nested groups excluded: {', '.join(sorted(nested))}")

    script_dir = os.path.dirname(os.path.abspath(__file__))
    output_file = os.path.join(script_dir, OUTPUT_PATH)
    entries, comments = read_existing_mappings(output_file)
    print(f"  {len(entries)} existing mappings, {sum(1 for t in entries.values() if t)} filled in")

    added = sorted(modules - entries.keys())
    for module in added:
        entries[module] = ""
        comments[module] = []

    # A module that has left the repository is also a human's call, so it stays.
    stale = sorted(entries.keys() - modules)

    write_mappings(output_file, entries, comments)
    print(f"Updated {output_file}")

    if stale:
        print(f"\nNOTE: {len(stale)} mapped modules are no longer published, and were kept.")
        print("      Removing one is a human's call too:")
        for module in stale:
            print(f"        {module}")

    # Both halves are fatal. They are counted apart only so that a long-ignored gap reads as
    # one, rather than hiding among whatever this run happened to discover.
    newly_added = added
    still_unmapped = sorted(m for m, t in entries.items() if not t and m not in set(added))
    if not newly_added and not still_unmapped:
        print(f"\nAll {len(entries)} modules are mapped.")
        return

    def report(line=""):
        print(line, file=sys.stderr)

    def report_modules(heading, modules):
        report()
        report(f"{heading}:")
        for module in modules:
            report(f"  {module}=")

    # Everything above went to stdout; without this the verdict can surface before it.
    sys.stdout.flush()
    total = len(newly_added) + len(still_unmapped)
    report(f"\n{'=' * 75}")
    report(f"FAILED: {total} of {len(entries)} modules have no mapping")
    report(f"{'=' * 75}")
    report("Each needs a human decision: the intellij-dependencies name to use, which may")
    report("well be its own. Being published there under its own name is NOT on its own a")
    report("reason to map it to itself - check the publication is frequent enough to")
    report("depend on. Record the reasoning in a comment above the entry.")
    if newly_added:
        report_modules(f"{len(newly_added)} newly discovered, added as blank", newly_added)
    if still_unmapped:
        report_modules(f"{len(still_unmapped)} left blank by an earlier run", still_unmapped)
    report()
    report(f"Fill these in in {os.path.relpath(output_file, script_dir)} and re-run.")
    sys.exit(EXIT_NEEDS_MAPPING)


if __name__ == "__main__":
    main()
